"""Frozen train-only consensus of material pair specialists and object detector."""
import datetime
import json
import time

import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.ensemble import ExtraTreesClassifier
from sklearn.metrics import balanced_accuracy_score
from threadpoolctl import threadpool_limits

from fewshot_train_only_probe import ROOT, NOTES, CLASSES, sha, dump, unit


def main():
    start = time.time()
    prefix = "pairwise_detector_consensus"
    protected = {p: sha(ROOT / p) for p in ["data/processed/manifest.csv",
                                          "data/preprocessing_inputs.npz",
                                          "final-submit/DSC2026_Notebook.ipynb"]}
    plan = {"method": "train_only_pairwise_plastic_all_material_consensus_v1",
            "training": "7 plastic-versus-material ExtraTrees experts fit on automatic pre-human train anchors plus34 lawful human sources",
            "development": "source-group-held-out OOF generated by pairwise_auto_experts_probe.py",
            "route": "matching old-category pair score>=.6 AND minimum all-seven pair scores>=.4 AND pretrained Plastic detector>=.65 with margin>=.05",
            "threshold_origin": "development choice on repeatedly used34 human sources, not independent validation",
            "guard": "OOF >=30/34 macro>=.9, >=2 routed human sources, all routed humans correct",
            "maximum_changes": 40,
            "test_rows": 0, "review_archive_read": False, "new_manual_labels": 0,
            "protected_sha256": protected, "source_code_sha256": sha(__file__),
            "evaluation_limit": "same34 sources repeatedly used; post-freeze audit may reveal regressions"}
    dump(NOTES / f"json/{prefix}_plan.json", plan)
    m = pd.read_csv(ROOT / "data/processed/manifest.csv", dtype={"parent_id": str})
    complete = m[m.split.eq("train") & ~m.is_crop].sort_values("parent_id").reset_index(drop=True)
    frame = complete[complete.training_eligible].reset_index(drop=True)
    keys = frame.parent_key.to_numpy(str)
    n = len(keys)
    assert n == 1904
    seeds = pd.read_csv(ROOT / "data/processed/manual_seeds.csv")
    lookup = dict(zip(keys, range(n)))
    pos = np.array([lookup[k] for k in seeds.key])
    gold = np.array([CLASSES.index(c) for c in seeds.assigned_class])
    assert len(pos) == 34 and seeds.assigned_class.value_counts().le(5).all()
    human = np.zeros(n, bool)
    human[pos] = True
    auto = pd.read_csv(NOTES / "table-csv/automatic_full_seed_targets.csv").set_index("key").loc[keys]
    target = np.array([CLASSES.index(c) for c in auto.automatic_class])
    target[pos] = gold
    fitmask = auto.automatic_anchor.to_numpy(bool) | human
    weight = np.clip(auto.reliable_vote_count.to_numpy(float) / 4, .25, 1.)
    weight[pos] = 8.
    z = np.load(NOTES / ".runtime/dinov3_base_train_features.npz", allow_pickle=False)
    c = np.load(NOTES / ".runtime/convnext_train_features.npz", allow_pickle=False)
    d = np.load(NOTES / ".runtime/litter_object_features.npz", allow_pickle=False)
    surf = np.load(NOTES / ".runtime/surface_train_features.npz", allow_pickle=False)
    assert all(np.array_equal(x["keys"], keys) for x in [z, c, d, surf])
    raw = unit(np.c_[z["features"][:, :768], z["features"][:, 1536:2304]].astype(np.float32))
    cnn = unit(c["features"].astype(np.float32))
    det = np.sqrt(np.maximum(d["detection_stats"], 0)).astype(np.float32)
    surface = surf["features"].astype(np.float32) / 255
    oof = pd.read_csv(NOTES / "table-csv/pairwise_auto_experts_probe_oof.csv").set_index("key").loc[seeds.key]
    d34 = d["detection_stats"][pos, :5]
    dvalid34 = (d34[:, 0] >= .65) & ((d34[:, 0] - d34[:, 1:].max(1)) >= .05)
    baseline = np.array([CLASSES.index(c) for c in oof.baseline_class])
    matched = oof.matching_expert_plastic_score.to_numpy(float)
    allmin = oof[[f"plastic_vs_{cl}" for cl in CLASSES if cl != "plastic"]].min(1).to_numpy(float)
    routed = (baseline != 4) & (matched >= .6) & (allmin >= .4) & dvalid34
    pred = np.where(routed, 4, baseline)
    matches = int((pred == gold).sum())
    macro = float(balanced_accuracy_score(gold, pred))
    count = int(routed.sum())
    right = int((routed & (gold == 4)).sum())
    guard = matches >= 30 and macro >= .9 - 1e-12 and count >= 2 and right == count
    summary = {"matches": matches, "macro": macro, "routed": count,
               "correct_routes": right, "guard": bool(guard)}
    scores = np.full((n, 8), np.nan, np.float32)
    with threadpool_limits(limits=4):
        pca = PCA(n_components=80, svd_solver="randomized", random_state=20261108).fit(raw)
        pcac = PCA(n_components=32, svd_solver="randomized", random_state=20261108).fit(cnn)
        x = np.c_[unit(pca.transform(raw)), unit(pcac.transform(cnn)), det, surface]
        for other in range(8):
            if other == 4:
                continue
            fit = np.flatnonzero(fitmask & np.isin(target, [other, 4]))
            expert = ExtraTreesClassifier(n_estimators=240, min_samples_leaf=2,
                                          max_features=.7, class_weight="balanced",
                                          n_jobs=4, random_state=20261108 + other)
            expert.fit(x[fit], (target[fit] == 4).astype(int), sample_weight=weight[fit])
            scores[:, other] = expert.predict_proba(x)[:, 1]
    current = np.array([CLASSES.index(c) for c in frame.assigned_class])
    pair_score = scores[np.arange(n), current]
    pair_score[current == 4] = 0
    all_score = np.nanmin(scores, axis=1)
    ds = d["detection_stats"][:, :5]
    detector_valid = (ds[:, 0] >= .65) & ((ds[:, 0] - ds[:, 1:].max(1)) >= .05)
    route = (current != 4) & (pair_score >= .6) & (all_score >= .4) & detector_valid
    priority = np.minimum.reduce([pair_score, all_score, ds[:, 0]])
    gate = route & ~human
    proposals = int(gate.sum())
    rank = np.argsort(-priority, kind="stable")
    selected = rank[gate[rank]][:40]
    gate[:] = False
    gate[selected] = True
    if not guard:
        gate[:] = False
    result = complete[["parent_key", "parent_id", "source_path", "source_sha256"]].rename(
        columns={"parent_key": "key", "parent_id": "image_id"}).copy()
    for dest, src in [("baseline_class", "assigned_class"), ("predicted_class", "assigned_class"),
                      ("category_source", "label_source"), ("category_score", "category_score"),
                      ("category_score_kind", "category_score_kind"),
                      ("human_reviewed", "human_reviewed"), ("needs_review", "needs_review")]:
        result[dest] = complete[src]
    result = result.set_index("key")
    for i in np.flatnonzero(gate):
        result.loc[keys[i], ["predicted_class", "category_source", "category_score",
                             "category_score_kind", "needs_review"]] = [
            "plastic", "pairwise_detector_consensus_snapshot", float(priority[i]),
            "uncalibrated_three_way_material_agreement", True]
    destination = NOTES / f"table-csv/{prefix}_selected.csv"
    result.reset_index().to_csv(destination, index=False)
    pd.DataFrame({"key": keys, "old_class": np.asarray(CLASSES)[current],
                  "matching_pair_score": pair_score, "minimum_all_pair_score": all_score,
                  "detector_plastic_score": ds[:, 0], "routed": route,
                  "accepted": gate}).to_csv(NOTES / f"table-csv/{prefix}_evidence.csv", index=False)
    active = json.loads((NOTES / "json/bounded_anchor_publication.json").read_text())["source_frozen_prefix"]
    report = json.loads((NOTES / f"json/{active}_frozen.json").read_text())
    initial = pd.read_csv(NOTES / "table-csv/bounded_consensus_selected.csv").set_index("key")
    report.update(status="frozen_before_private_pairwise_detector_audit",
                  method=plan["method"], prediction_sha256=sha(destination),
                  protected_sha256=protected, primary_head=summary,
                  primary_plan_sha256=sha(NOTES / f"json/{prefix}_plan.json"),
                  selected_heads=[summary], qualified_heads=[summary] if guard else [],
                  selected_knn_heads=[], human_leave_source_group_out_matches=matches,
                  human_holdout_rows=34, development_balanced_recall=macro,
                  confidence_calibration={"selected": summary, "independent_validation": False},
                  accepted_by_development_guard=bool(guard), proposed_new_labels=proposals,
                  changed_rows_vs_baseline=int(gate.sum()), new_neural_changes=0,
                  new_vit_propagation_changes=0,
                  cumulative_changes_vs_initial_program=int(result.predicted_class.ne(
                      initial.loc[result.index, "baseline_class"]).sum()),
                  source_counts=result.category_source.value_counts().to_dict(),
                  source_code_sha256=sha(__file__), seconds=time.time()-start,
                  validation_limit=plan["evaluation_limit"])
    assert all(sha(ROOT / p) == digest for p, digest in protected.items())
    dump(NOTES / f"json/{prefix}_frozen.json", report)
    dump(NOTES / f"json/{prefix}_publication_decision.json", {
        "decision": "publish" if guard else "reject", "prediction_sha256": sha(destination),
        "accepted_changes": int(gate.sum()),
        "timestamp_utc": datetime.datetime.now(datetime.timezone.utc).isoformat()})
    print(json.dumps({**summary, "proposals": proposals, "accepted_changes": int(gate.sum()),
                      "seconds": round(time.time()-start, 1)}, indent=2), flush=True)


if __name__ == "__main__":
    main()
